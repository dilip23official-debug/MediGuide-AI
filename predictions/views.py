from pathlib import Path
import joblib

from django.conf import settings
from rest_framework import viewsets, status
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework.decorators import action

from .models import Prediction
from .serializers import PredictionSerializer


MODEL_PATH = (
    Path(settings.BASE_DIR)
    / "ml_model"
    / "diabetes"
    / "diabetes_model.joblib"
)

diabetes_model = joblib.load(MODEL_PATH)


class PredictionViewSet(viewsets.ReadOnlyModelViewSet):
    serializer_class = PredictionSerializer
    permission_classes = [IsAuthenticated]

    def get_queryset(self):
        return Prediction.objects.filter(
            user=self.request.user
        ).order_by("-created_at")

    @action(detail=False, methods=["post"], url_path="diabetes")
    def diabetes_prediction(self, request):
        required_fields = [
            "pregnancies",
            "glucose",
            "blood_pressure",
            "skin_thickness",
            "insulin",
            "bmi",
            "diabetes_pedigree",
            "age",
        ]

        for field in required_fields:
            if field not in request.data:
                return Response(
                    {"detail": f"{field} is required."},
                    status=status.HTTP_400_BAD_REQUEST,
                )

        try:
            pregnancies = float(request.data["pregnancies"])
            glucose = float(request.data["glucose"])
            blood_pressure = float(request.data["blood_pressure"])
            skin_thickness = float(request.data["skin_thickness"])
            insulin = float(request.data["insulin"])
            bmi = float(request.data["bmi"])
            diabetes_pedigree = float(request.data["diabetes_pedigree"])
            age = float(request.data["age"])

        except (ValueError, TypeError):
            return Response(
                {"detail": "All prediction values must be numbers."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        features = [[
            pregnancies,
            glucose,
            blood_pressure,
            skin_thickness,
            insulin,
            bmi,
            diabetes_pedigree,
            age,
        ]]

        try:
            prediction_result = diabetes_model.predict(features)[0]
            probabilities = diabetes_model.predict_proba(features)[0]

            probability = float(probabilities[1])

            if prediction_result == 1:
                result = "Higher risk"
            else:
                result = "Lower risk"

        except Exception as e:
            return Response(
                {
                    "detail": "ML prediction failed.",
                    "error": str(e),
                },
                status=status.HTTP_500_INTERNAL_SERVER_ERROR,
            )

        prediction = Prediction.objects.create(
            user=request.user,
            prediction_type="Diabetes Risk",
            result=result,
            probability=probability,
        )

        return Response(
            {
                "id": prediction.id,
                "prediction_type": prediction.prediction_type,
                "result": result,
                "probability": round(probability, 4),
                "message": (
                    "This is an educational risk estimate "
                    "generated by a machine learning model. "
                    "It is not a medical diagnosis."
                ),
            },
            status=status.HTTP_200_OK,
        )